// Size of Data Types
#include <stdio.h>

int main()
{
     char a;
     int b;
     float c;
     double d;

     printf("The size of a is: %lu\n", sizeof(a));
     printf("The size of b is: %lu\n", sizeof(b));
     printf("The size of c is: %lu\n", sizeof(c));
     printf("The size of d is: %lu\n", sizeof(d));

     return 0;
}